-- =============================================================================
-- NewVim - config/options.lua
-- =============================================================================
-- Qui vivono le tue preferenze personali.
--
-- Regola pratica:
-- - `config/defaults.lua` = default “generici” tipo LazyVim
-- - `config/options.lua`  = override *specifici* dell'utente
-- =============================================================================

require("config.defaults")

-- -----------------------------------------------------------------------------
-- Spell
-- -----------------------------------------------------------------------------
vim.o.spelllang = "en_us,it"
vim.o.spell = true

-- -----------------------------------------------------------------------------
-- UI / numeri di riga
-- -----------------------------------------------------------------------------
vim.opt.relativenumber = false

-- -----------------------------------------------------------------------------
-- Cmdline completion
-- -----------------------------------------------------------------------------
-- Richiesta: niente autocomplete “popup” mentre scrivi comandi.
-- Manteniamo comunque la completion classica (TAB) ma senza pum.
vim.opt.wildoptions = {}

-- -----------------------------------------------------------------------------
-- Autoformat
-- -----------------------------------------------------------------------------
vim.g.autoformat = false

-- -----------------------------------------------------------------------------
-- File explorer
-- -----------------------------------------------------------------------------
vim.g.nvim_tree_respect_buf_cwd = 1

-- -----------------------------------------------------------------------------
-- Whitespace
-- -----------------------------------------------------------------------------
vim.opt.list = true
vim.opt.listchars = { space = "⋅", tab = "→ " }

-- -----------------------------------------------------------------------------
-- Root detection
-- -----------------------------------------------------------------------------
vim.g.root_spec = { "lsp", { "package.json", ".git", "lua" }, "cwd" }

-- -----------------------------------------------------------------------------
-- Folding
-- -----------------------------------------------------------------------------
vim.opt.foldlevel = 99
vim.opt.foldexpr = "v:lua.vim.treesitter.foldexpr()"
vim.opt.foldmethod = "expr"

-- -----------------------------------------------------------------------------
-- Conceal
-- -----------------------------------------------------------------------------
vim.opt.conceallevel = 0

-- -----------------------------------------------------------------------------
-- Filetype extra
-- -----------------------------------------------------------------------------
-- Alcune estensioni non sono sempre mappate dal core.
vim.filetype.add({
  extension = {
    prisma = "prisma",
  },
})
